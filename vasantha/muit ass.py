# Multiple assignment of different values
a, b, c = 10, 20, 30

print("After assigning different values:")
print("a =", a)
print("b =", b)
print("c =", c)

# Assigning the same value to all variables in one line
a = b = c = 100

print("\nAfter assigning the same value:")
print("a =", a)
print("b =", b)
print("c =", c)
#output:After assigning different values:
#a = 10
#b = 20
#c = 30

#After assigning the same value:
#a = 100
#b = 100
#c = 100