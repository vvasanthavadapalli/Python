# Demonstrating dynamic typing in Python

value = 100
print("Value:", value)
print("Type:", type(value))

# Reassign the same variable to a string
value = "Hello, Python!"
print("\nValue:", value)
print("Type:", type(value))
#output:Value: 100
#Type: <class 'int'>

#Value: Hello, Python!
#Type: <class 'str'>